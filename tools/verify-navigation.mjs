// Run against the web assets shipped in a release APK. All fixture data stays on localhost.
import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import { createServer } from 'node:http'
import { extname, resolve, sep } from 'node:path'
import { chromium } from 'playwright'

async function verifyMemoryOrigins(page, back) {
  const drawer = page.locator('[class^="drawer-"]')
  const front = name => page.locator(`[data-settings-route="${name}"][data-route-position="front"]:visible`)
  const button = (parent, name) => parent.getByRole('button', { name, exact: true })
  const closeSettings = () => page.locator('[data-settings-shell]').waitFor({ state: 'detached' })
  await button(page, '打开边栏').click()
  await button(drawer, '收藏').click()
  const favorites = drawer.locator('.lib-favorites')
  await favorites.waitFor()
  await button(drawer, '记忆').click()
  await front('memory').waitFor()
  assert.equal(await page.locator('[data-settings-route="root"]').count(), 0, 'direct entry has no synthetic settings root')
  await back()
  await closeSettings()
  assert.equal(await drawer.getAttribute('aria-hidden'), 'false')
  await favorites.waitFor()
  // Use the other Back affordance on the identical entry point.
  await button(drawer, '记忆').click()
  await front('memory').locator('header button').click()
  await closeSettings()
  await favorites.waitFor()
  await button(drawer, '设置').click()
  await button(front('root'), '记忆').click()
  await front('memory').waitFor()
  const add = button(front('memory'), '添加记忆')
  await add.click()
  const editor = page.locator('[data-modal-surface]:visible').last()
  await editor.waitFor()
  await back()
  await editor.waitFor({ state: 'detached' })
  await front('memory').waitFor()
  await front('memory').locator('header button').click()
  await page.locator('[data-settings-route="memory"]').waitFor({ state: 'detached' })
  await front('root').waitFor()
  await back()
  await closeSettings()
  await favorites.waitFor()
  await back()
  await favorites.waitFor({ state: 'detached' })
  await back()
  await page.waitForFunction(() => document.querySelector('[class^="drawer-"]')?.getAttribute('aria-hidden') === 'true')
  console.log('PASS drawer → memory → drawer with favorites preserved, settings → memory editor → memory → settings → drawer → chat')
}

